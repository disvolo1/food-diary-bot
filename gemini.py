# JSON PARSER
# ============================================================

def extract_json(text: str):

    if not text:
        raise ValueError(
            "Gemini returned an empty response"
        )

    text = text.strip()

    # Убираем markdown, если Gemini всё-таки его добавил
    text = re.sub(
        r"^```json\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"^```\s*",
        "",
        text
    )

    text = re.sub(
        r"\s*```$",
        "",
        text
    )

    text = text.strip()

    # Сначала пробуем распарсить весь ответ
    try:
        return json.loads(text)

    except json.JSONDecodeError:
        pass

    # Если Gemini добавил какой-то текст,
    # пытаемся найти JSON внутри ответа
    match = re.search(
        r"\{.*\}",
        text,
        re.DOTALL
    )

    if not match:

        raise ValueError(
            f"Gemini did not return valid JSON: {text}"
        )

    json_text = match.group(0)

    try:

        return json.loads(
            json_text
        )

    except json.JSONDecodeError as error:

        raise ValueError(
            f"Invalid JSON from Gemini: {json_text}"
        ) from error


# ============================================================
# ANALYZE FOOD IMAGE
# ============================================================

async def analyze_food_image(
    image_bytes: bytes,
    mime_type: str = "image/jpeg"
):
    """
    Отправляет фотографию этикетки в Gemini
    и получает структурированные данные КБЖУ.
    """

    if not image_bytes:

        raise ValueError(
            "Empty image"
        )

    logging_message = (
        f"Sending image to Gemini: "
        f"{len(image_bytes)} bytes, "
        f"MIME={mime_type}, "
        f"MODEL={MODEL_NAME}"
    )

    print(logging_message)

    try:

        response = await client.aio.models.generate_content(

            model=MODEL_NAME,

            contents=[
                types.Part.from_bytes(
                    data=image_bytes,
                    mime_type=mime_type
                ),
                PROMPT
            ],

            config=types.GenerateContentConfig(

                response_mime_type="application/json"
            )
        )

    except Exception as error:

        print(
            f"Gemini API error: {error}"
        )

        raise


    if not response.text:

        raise ValueError(
            "Gemini returned an empty response"
        )


    print(
        "GEMINI RAW RESPONSE:",
        response.text
    )


    data = extract_json(
        response.text
    )


    # ========================================================
    # ПРОВЕРЯЕМ ПОЛЯ
    # ========================================================

    required_fields = [
        "name",
        "calories",
        "protein",
        "fat",
        "carbs",
        "basis"
    ]


    for field in required_fields:

        if field not in data:

            raise ValueError(
                f"Gemini response is missing: {field}"
            )


    # ========================================================
    # НОРМАЛИЗАЦИЯ ЧИСЕЛ
    # ========================================================

    numeric_fields = [
        "calories",
        "protein",
        "fat",
        "carbs"
    ]


    for field in numeric_fields:

        value = data.get(field)

        if value is None:
            continue

        try:

            data[field] = float(
                str(value).replace(",", ".")
            )

        except (
            ValueError,
            TypeError
        ):

            print(
                f"Invalid numeric value "
                f"for {field}: {value}"
            )

            data[field] = None


    # ========================================================
    # НОРМАЛИЗАЦИЯ BASIS
    # ========================================================

    allowed_basis = {
        "100g",
        "100ml",
        "portion",
        "package"
    }


    if data["basis"] not in allowed_basis:

        data["basis"] = None


    # ========================================================
    # НОРМАЛИЗАЦИЯ NAME
    # ========================================================

    if not data.get("name"):

        data["name"] = "Неизвестный продукт"


    data["name"] = str(
        data["name"]
    ).strip()


    print(
        "GEMINI PARSED RESULT:",
        data
    )


    return data
