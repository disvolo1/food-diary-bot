# ANALYZE FOOD IMAGE
# ============================================================

async def analyze_food_image(
    image_bytes: bytes,
    mime_type: str = "image/jpeg"
):

    if not image_bytes:

        raise ValueError(
            "Empty image"
        )


    # ========================================================
    # DEBUG LOG
    # ========================================================

    print(
        "=================================================="
    )

    print(
        "GEMINI FOOD ANALYSIS"
    )

    print(
        f"Model: {MODEL_NAME}"
    )

    print(
        f"Image size: {len(image_bytes)} bytes"
    )

    print(
        f"MIME type: {mime_type}"
    )

    print(
        "=================================================="
    )


    # ========================================================
    # SEND IMAGE
    # ========================================================

    try:

        response = await client.aio.models.generate_content(

            model=MODEL_NAME,

            contents=[
                types.Part.from_bytes(
                    data=image_bytes,
                    mime_type=mime_type
                ),

                PROMPT
            ],

            config=types.GenerateContentConfig(

                response_mime_type="application/json"

            )
        )


    except Exception as error:

        print(
            "=================================================="
        )

        print(
            "GEMINI API ERROR"
        )

        print(
            repr(error)
        )

        print(
            "=================================================="
        )

        raise


    # ========================================================
    # EMPTY RESPONSE
    # ========================================================

    if not response.text:

        raise ValueError(
            "Gemini returned an empty response"
        )


    # ========================================================
    # RAW RESPONSE
    # ========================================================

    print(
        "GEMINI RAW RESPONSE:"
    )

    print(
        response.text
    )


    # ========================================================
    # PARSE JSON
    # ========================================================

    data = extract_json(
        response.text
    )


    # ========================================================
    # REQUIRED FIELDS
    # ========================================================

    required_fields = [
        "name",
        "calories",
        "protein",
        "fat",
        "carbs",
        "basis"
    ]


    for field in required_fields:

        if field not in data:

            raise ValueError(
                f"Gemini response is missing: {field}"
            )


    # ========================================================
    # NUMERIC VALUES
    # ========================================================

    numeric_fields = [
        "calories",
        "protein",
        "fat",
        "carbs"
    ]


    for field in numeric_fields:

        value = data.get(field)


        if value is None:

            continue


        try:

            # Поддерживаем:
            # 12.5
            # "12.5"
            # "12,5"

            data[field] = float(
                str(value).replace(
                    ",",
                    "."
                )
            )


        except (
            ValueError,
            TypeError
        ):

            print(
                f"Invalid {field} value: {value}"
            )

            data[field] = None


    # ========================================================
    # BASIS VALIDATION
    # ========================================================

    allowed_basis = {
        "100g",
        "100ml",
        "portion",
        "package"
    }


    if data.get("basis") not in allowed_basis:

        data["basis"] = None


    # ========================================================
    # NAME VALIDATION
    # ========================================================

    if not data.get("name"):

        data["name"] = "Неизвестный продукт"

    else:

        data["name"] = str(
            data["name"]
        ).strip()


    # ========================================================
    # FINAL RESULT
    # ========================================================

    print(
        "GEMINI PARSED RESULT:"
    )

    print(
        json.dumps(
            data,
            ensure_ascii=False,
            indent=2
        )
    )

    print(
        "=================================================="
    )


    return data
